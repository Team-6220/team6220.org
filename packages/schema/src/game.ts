import { Type, type Static } from "@sinclair/typebox";
import { Alliance, Num, Pose, Shape, Vec2 } from "./common.js";

export const GAME_SCHEMA_VERSION = 1;

// ---------------------------------------------------------------------------
// game.json — metadata, timeline, threshold profiles
// ---------------------------------------------------------------------------

export const ElementActivity = Type.Union(
  [Type.Literal("both"), Type.Literal("none"), Type.Literal("groupA"), Type.Literal("groupB")],
  {
    description:
      "Which alliances' copies of an element are active in this phase. groupA/groupB are alliances chosen at runtime by the game's groupsHook (e.g. REBUILT shift order).",
  },
);

export const Phase = Type.Object(
  {
    id: Type.String({ minLength: 1, description: "e.g. AUTO, TRANSITION, SHIFT_1, END_GAME" }),
    label: Type.String(),
    duration: Num("seconds", { minimum: 0 }),
    period: Type.Union([Type.Literal("auto"), Type.Literal("teleop")], {
      description: "Scoring period this phase belongs to.",
    }),
    robotsEnabled: Type.Boolean({ description: "false for scoring-only gaps where robots are disabled." }),
    elementActive: Type.Optional(
      Type.Record(Type.String(), ElementActivity, {
        description: "Base element id (without alliance suffix) -> which alliance copies are active.",
      }),
    ),
    assessClimbAtEnd: Type.Optional(
      Type.Boolean({ description: "Emit climb_assessed for every climbed robot when this phase ends." }),
    ),
  },
  { description: "One step of the match timeline." },
);
export type Phase = Static<typeof Phase>;

export const GameMeta = Type.Object(
  {
    schemaVersion: Type.Literal(GAME_SCHEMA_VERSION),
    id: Type.String({ minLength: 1, description: "e.g. rebuilt-2026" }),
    name: Type.String(),
    year: Type.Integer(),
    version: Type.String({ description: "Module version (semver)." }),
    manualVersion: Type.String({ description: "Game manual version the module was built from, e.g. TU22." }),
    robotsPerAlliance: Type.Integer({ minimum: 1 }),
    timeline: Type.Object({
      phases: Type.Array(Phase, { minItems: 1 }),
      postMatchAssessment: Num("seconds after the last phase during which in-flight pieces still score", {
        minimum: 0,
      }),
    }),
    activationGrace: Num("seconds an element keeps scoring after it deactivates (assessment delay)", {
      minimum: 0,
    }),
    groupsHook: Type.Optional(
      Type.String({ description: "Id of a reviewed TypeScript hook that decides groupA/groupB at runtime." }),
    ),
    thresholdProfiles: Type.Record(Type.String(), Type.Record(Type.String(), Type.Number()), {
      description: "Named sets of bonus ranking point thresholds, e.g. regional / districtChampionship.",
    }),
    defaultProfile: Type.String(),
  },
  { description: "game.json: match metadata and timeline." },
);
export type GameMeta = Static<typeof GameMeta>;

// ---------------------------------------------------------------------------
// field.json — field size and elements
// ---------------------------------------------------------------------------

const ElementBase = {
  id: Type.String({ minLength: 1, description: "Unique id. Mirrored copies get '.red' / '.blue' suffixes." }),
  label: Type.Optional(Type.String()),
  alliance: Type.Optional(Alliance),
  mirror: Type.Optional(
    Type.Boolean({
      description:
        "If true, the element is authored for blue and a red copy is generated by the field's mirror rule. Ids become '<id>.blue' and '<id>.red'.",
    }),
  ),
  visual: Type.Optional(
    Type.Object({
      fill: Type.Optional(Type.String({ description: "Theme token name (e.g. 'gray-4') or CSS color." })),
      label: Type.Optional(Type.Boolean()),
    }),
  ),
};

export const WallElement = Type.Object(
  { ...ElementBase, kind: Type.Literal("wall"), shape: Shape },
  { description: "Static collider (guardrails, structure posts)." },
);

export const ZoneElement = Type.Object(
  {
    ...ElementBase,
    kind: Type.Literal("zone"),
    shape: Shape,
    tags: Type.Optional(Type.Array(Type.String())),
  },
  { description: "Named region used by rules and agents. Not a collider." },
);

export const TerrainElement = Type.Object(
  {
    ...ElementBase,
    kind: Type.Literal("terrain"),
    shape: Shape,
    speedFactor: Num("multiplier on robot top speed while on this terrain", { minimum: 0, maximum: 1 }),
    accelFactor: Num("multiplier on robot acceleration while on this terrain", { minimum: 0, maximum: 1 }),
    blocksPieces: Type.Optional(Type.Boolean({ description: "If true, free pieces collide with this terrain." })),
  },
  { description: "Region that slows robots (e.g. a bump or ramp)." },
);

export const GateElement = Type.Object(
  {
    ...ElementBase,
    kind: Type.Literal("gate"),
    shape: Shape,
    clearance: Num("height in meters; robots taller than this cannot pass", { exclusiveMinimum: 0 }),
  },
  { description: "Passage with a height limit (e.g. under a trench)." },
);

export const SinkElement = Type.Object(
  {
    ...ElementBase,
    kind: Type.Literal("sink"),
    shape: Shape,
    solid: Type.Boolean({ description: "If true, the shape is also a collider." }),
    target: Type.Object({
      shape: Shape,
      description: Type.Optional(Type.String()),
      height: Type.Optional(
        Num("height of the scoring opening above the carpet, meters (default 0 = a floor-level goal)", { minimum: 0 }),
      ),
      entry: Type.Optional(
        Type.Union([Type.Literal("top"), Type.Literal("front")], {
          description:
            "top: pieces must be falling when they pass through the opening (e.g. a funnel). front: any crossing of the opening height counts (e.g. a wall slot). Default top.",
        }),
      ),
    }),
    scoresFor: Type.Optional(Alliance),
    emit: Type.Optional(
      Type.Object({
        delay: Num("seconds between a piece entering and being re-emitted", { minimum: 0 }),
        exits: Type.Array(
          Type.Object({ x: Type.Number(), y: Type.Number(), theta: Type.Number(), speed: Num("m/s") }),
          { minItems: 1, description: "One exit is chosen per piece with the match's seeded RNG." },
        ),
        spread: Num("random heading spread at the exit, radians", { minimum: 0 }),
      }),
    ),
  },
  { description: "Goal that consumes pieces shot into its target and optionally re-emits them (e.g. the Hub)." },
);

export const FeederElement = Type.Object(
  {
    ...ElementBase,
    kind: Type.Literal("feeder"),
    shape: Shape,
    exit: Pose,
    speed: Num("piece exit speed, m/s", { minimum: 0 }),
    stock: Num("pieces available at match start", { minimum: 0 }),
    capacity: Num("maximum stock", { minimum: 0 }),
    rate: Num("pieces per second the human player can deliver", { exclusiveMinimum: 0 }),
    accuracy: Num("heading spread in radians", { minimum: 0 }),
    mode: Type.Union([Type.Literal("onDemand"), Type.Literal("auto")], {
      description: "onDemand: delivers while a robot of the same alliance is in triggerZone. auto: delivers whenever stocked.",
    }),
    triggerZone: Type.Optional(Shape),
    absorbZone: Type.Optional(Type.Object({ shape: Shape }, { description: "Free pieces entering here return to stock." })),
    enabledInAuto: Type.Optional(Type.Boolean()),
  },
  { description: "Human-player model that introduces pieces." },
);

export const ClimbStructureElement = Type.Object(
  {
    ...ElementBase,
    kind: Type.Literal("climbStructure"),
    shape: Shape,
    solid: Type.Boolean(),
    engageZone: Shape,
    levels: Type.Array(Type.Object({ level: Type.Integer({ minimum: 1 }), label: Type.String() }), { minItems: 1 }),
  },
  { description: "Endgame structure (e.g. Tower). Robots with a climber inside engageZone can climb." },
);

export const PieceSourceElement = Type.Object(
  {
    ...ElementBase,
    kind: Type.Literal("pieceSource"),
    shape: Shape,
    piece: Type.String({ description: "Piece type id from pieces.json." }),
    count: Type.Union([Type.Integer({ minimum: 0 }), Type.Literal("remainder")], {
      description: "Number of pieces, or 'remainder' for totalCount minus all other placements and preloads.",
    }),
    layout: Type.Union([Type.Literal("grid"), Type.Literal("random")]),
    gapAlongX: Type.Optional(Num("empty strip in the middle of a grid (e.g. a removed divider), meters")),
  },
  { description: "Initial piece placement." },
);

export const FieldElement = Type.Union([
  WallElement,
  ZoneElement,
  TerrainElement,
  GateElement,
  SinkElement,
  FeederElement,
  ClimbStructureElement,
  PieceSourceElement,
]);
export type FieldElement = Static<typeof FieldElement>;
export type FieldElementKind = FieldElement["kind"];

export const Objective = Type.Object(
  {
    id: Type.String(),
    pose: Pose,
    alliance: Type.Optional(Alliance),
    mirror: Type.Optional(Type.Boolean()),
    description: Type.Optional(Type.String()),
  },
  { description: "Named location agents can navigate to (e.g. a scoring pose)." },
);
export type Objective = Static<typeof Objective>;

export const FieldDef = Type.Object(
  {
    length: Num("field length along x, meters", { exclusiveMinimum: 0 }),
    width: Num("field width along y, meters", { exclusiveMinimum: 0 }),
    mirror: Type.Union([Type.Literal("rotational"), Type.Literal("reflective")], {
      description: "How red copies are generated from blue: rotate 180 degrees about field center, or reflect across x = length/2.",
    }),
    centerLineX: Num("x of the center line, meters"),
    elements: Type.Array(FieldElement),
    startPositions: Type.Array(Pose, { minItems: 1, description: "Blue start poses; red ones are mirrored." }),
    objectives: Type.Array(Objective),
  },
  { description: "field.json" },
);
export type FieldDef = Static<typeof FieldDef>;

// ---------------------------------------------------------------------------
// pieces.json
// ---------------------------------------------------------------------------

export const PieceType = Type.Object({
  id: Type.String(),
  label: Type.String(),
  shape: Type.Literal("circle"),
  radius: Num("meters", { exclusiveMinimum: 0 }),
  mass: Num("kg", { exclusiveMinimum: 0 }),
  restitution: Num("bounciness 0-1", { minimum: 0, maximum: 1 }),
  friction: Num("surface friction", { minimum: 0 }),
  linearDamping: Num("rolling resistance on carpet, 1/s", { minimum: 0 }),
  color: Type.Optional(Type.String()),
});
export type PieceType = Static<typeof PieceType>;

export const PiecesDef = Type.Object(
  {
    types: Type.Array(PieceType, { minItems: 1 }),
    totalCount: Type.Integer({ minimum: 0, description: "Pieces staged per match." }),
    preload: Type.Object({ piece: Type.String(), max: Type.Integer({ minimum: 0 }) }),
  },
  { description: "pieces.json" },
);
export type PiecesDef = Static<typeof PiecesDef>;

// ---------------------------------------------------------------------------
// scoring.json — declarative rules
// ---------------------------------------------------------------------------

export const EventType = Type.Union(
  [
    Type.Literal("piece_scored"),
    Type.Literal("climb_assessed"),
    Type.Literal("foul"),
    Type.Literal("piece_acquired"),
    Type.Literal("shot_launched"),
    Type.Literal("phase_start"),
    Type.Literal("phase_end"),
  ],
  { description: "Match event that can trigger a scoring rule." },
);

export const Condition = Type.Object(
  {
    field: Type.String({ description: "Event field, e.g. target, active, period, phase, level, alliance." }),
    op: Type.Union([
      Type.Literal("eq"),
      Type.Literal("neq"),
      Type.Literal("in"),
      Type.Literal("gte"),
      Type.Literal("lte"),
    ]),
    value: Type.Union([Type.String(), Type.Number(), Type.Boolean(), Type.Array(Type.Union([Type.String(), Type.Number()]))]),
  },
  { description: "Condition on an event field. All conditions of a rule must hold." },
);
export type Condition = Static<typeof Condition>;

export const Effect = Type.Object(
  {
    points: Type.Optional(Type.Number({ description: "Points to add." })),
    to: Type.Optional(
      Type.Union([Type.Literal("event"), Type.Literal("opponent")], {
        description: "Who receives points/counters: the event's alliance (default) or its opponent.",
      }),
    ),
    counter: Type.Optional(Type.String({ description: "Per-alliance counter to increment, e.g. fuelActive." })),
    by: Type.Optional(Type.Number({ description: "Counter increment (default 1)." })),
    category: Type.Optional(
      Type.Union([Type.Literal("auto"), Type.Literal("teleop"), Type.Literal("endgame"), Type.Literal("foul")], {
        description: "Score breakdown bucket (default: the event's period).",
      }),
    ),
  },
  { description: "What a rule does when it fires." },
);
export type Effect = Static<typeof Effect>;

export const ScoringRule = Type.Object(
  {
    id: Type.String(),
    label: Type.String(),
    on: EventType,
    when: Type.Optional(Type.Array(Condition)),
    effects: Type.Array(Effect, { minItems: 1 }),
    limitPerAlliance: Type.Optional(Type.Integer({ minimum: 1, description: "Maximum firings per alliance per match." })),
    source: Type.Optional(Type.String({ description: "Manual section, e.g. '§6.5.2 Table 6-4'." })),
  },
  { description: "Event-driven scoring rule." },
);
export type ScoringRule = Static<typeof ScoringRule>;

export const ScoringDef = Type.Object(
  {
    fouls: Type.Record(Type.String(), Type.Number(), { description: "Foul severity -> points to the opponent." }),
    rules: Type.Array(ScoringRule),
    rankingPoints: Type.Object({
      win: Type.Number(),
      tie: Type.Number(),
      bonus: Type.Array(
        Type.Object({
          id: Type.String(),
          label: Type.String(),
          counter: Type.String({ description: "Alliance counter compared against the threshold." }),
          thresholdKey: Type.String({ description: "Key into the selected threshold profile." }),
        }),
      ),
    }),
  },
  { description: "scoring.json" },
);
export type ScoringDef = Static<typeof ScoringDef>;

// ---------------------------------------------------------------------------
// rules.json — coverage status and objective foul detectors
// ---------------------------------------------------------------------------

export const Detector = Type.Union(
  [
    Type.Object(
      {
        type: Type.Literal("crossLine"),
        lineX: Num("blue-relative x of the line, meters (mirrored for red)"),
        periods: Type.Array(Type.Union([Type.Literal("auto"), Type.Literal("teleop")])),
        completely: Type.Boolean({ description: "Foul only when the whole robot footprint is past the line." }),
      },
      { description: "Robot crosses past a line toward the opponent." },
    ),
    Type.Object(
      {
        type: Type.Literal("launchOutsideZone"),
        zone: Type.String({ description: "Base zone id (alliance copy of the shooter's alliance is used)." }),
        target: Type.String({ description: "Base sink id; only shots at the shooter's own copy count." }),
      },
      { description: "Robot launches at its target while bumpers are not at least partly in the zone." },
    ),
    Type.Object(
      { type: Type.Literal("pieceOutOfField") },
      { description: "A piece the robot launched lands outside the field." },
    ),
  ],
  { description: "Objective in-match rule check the sim can run." },
);
export type Detector = Static<typeof Detector>;

export const RuleCoverage = Type.Object({
  id: Type.String({ description: "Manual rule number, e.g. G403." }),
  topic: Type.String(),
  status: Type.Union([Type.Literal("implemented"), Type.Literal("approximated"), Type.Literal("not_implemented")]),
  reason: Type.Optional(Type.String()),
  penalty: Type.Optional(Type.String({ description: "Foul severity key from scoring.json fouls." })),
  detector: Type.Optional(Detector),
});
export type RuleCoverage = Static<typeof RuleCoverage>;

export const RulesDef = Type.Object({ rules: Type.Array(RuleCoverage) }, { description: "rules.json" });
export type RulesDef = Static<typeof RulesDef>;

// ---------------------------------------------------------------------------
// mechanisms.json, named-commands.json, stats.json
// ---------------------------------------------------------------------------

export const CustomMechanismType = Type.Object({
  id: Type.String(),
  base: Type.String({ description: "Core mechanism type this composes." }),
  label: Type.String(),
  defaults: Type.Record(Type.String(), Type.Union([Type.Number(), Type.Boolean(), Type.String()])),
  color: Type.Optional(Type.String()),
});
export const MechanismsDef = Type.Object({ types: Type.Array(CustomMechanismType) }, { description: "mechanisms.json" });
export type MechanismsDef = Static<typeof MechanismsDef>;

export const NamedCommand = Type.Object({
  action: Type.String({ description: "Driver action name, e.g. shoot, intake, climb." }),
  mechanism: Type.Optional(Type.String()),
  state: Type.Optional(Type.Union([Type.Literal("on"), Type.Literal("off")])),
  durationSeconds: Type.Optional(Type.Number({ minimum: 0 })),
  level: Type.Optional(Type.Integer({ minimum: 1 })),
});
export type NamedCommand = Static<typeof NamedCommand>;
export const NamedCommandsDef = Type.Object(
  { namedCommands: Type.Record(Type.String(), NamedCommand) },
  { description: "named-commands.json: PathPlanner named command -> sim action." },
);
export type NamedCommandsDef = Static<typeof NamedCommandsDef>;

export const StatDef = Type.Object({
  id: Type.String(),
  label: Type.String(),
  event: Type.String({ description: "Event type to count." }),
  when: Type.Optional(Type.Array(Condition)),
  sumField: Type.Optional(Type.String({ description: "Sum this numeric event field instead of counting." })),
  per: Type.Union([Type.Literal("robot"), Type.Literal("alliance")]),
});
export type StatDef = Static<typeof StatDef>;
export const StatsDef = Type.Object({ stats: Type.Array(StatDef) }, { description: "stats.json" });
export type StatsDef = Static<typeof StatsDef>;

// ---------------------------------------------------------------------------
// The assembled module
// ---------------------------------------------------------------------------

export interface GameModuleData {
  game: GameMeta;
  field: FieldDef;
  pieces: PiecesDef;
  scoring: ScoringDef;
  rules: RulesDef;
  mechanisms: MechanismsDef;
  namedCommands: NamedCommandsDef;
  stats: StatsDef;
}

export const GameModuleFiles = {
  "game.json": GameMeta,
  "field.json": FieldDef,
  "pieces.json": PiecesDef,
  "scoring.json": ScoringDef,
  "rules.json": RulesDef,
  "mechanisms.json": MechanismsDef,
  "named-commands.json": NamedCommandsDef,
  "stats.json": StatsDef,
} as const;

