// Writes every JSON Schema to docs/schemas/ and regenerates docs/SCHEMAS.md from them,
// so the docs can never drift from the code.
// Usage: npm run export-schemas

import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { TSchema } from "@sinclair/typebox";
import { RobotDesign } from "../robot.js";
import { Replay } from "../replay.js";
import { GameModuleFiles } from "../game.js";

const root = resolve(process.argv[2] ?? ".");
const outDir = join(root, "docs", "schemas");
mkdirSync(outDir, { recursive: true });

const schemas: { name: string; file: string; schema: TSchema; what: string }[] = [
  { name: "Robot design", file: "robot.schema.json", schema: RobotDesign, what: "A 2D robot: chassis, drivetrain, mounted mechanisms." },
  ...Object.entries(GameModuleFiles).map(([fileName, schema]) => ({
    name: `Game module: ${fileName}`,
    file: fileName.replace(/\.json$/, ".schema.json"),
    schema: schema as TSchema,
    what: (schema as { description?: string }).description ?? fileName,
  })),
  { name: "Replay", file: "replay.schema.json", schema: Replay, what: "Seed + versions + input log; re-simulates deterministically." },
];

/** Strips TypeBox's internal symbol keys by round-tripping through JSON. */
const plain = (s: TSchema) => JSON.parse(JSON.stringify(s));

for (const s of schemas) {
  const json = { $schema: "http://json-schema.org/draft-07/schema#", title: s.name, ...plain(s.schema) };
  writeFileSync(join(outDir, s.file), JSON.stringify(json, null, 2) + "\n");
}

// ---------------------------------------------------------------------------
// SCHEMAS.md
// ---------------------------------------------------------------------------

type Node = {
  type?: string;
  description?: string;
  properties?: Record<string, Node>;
  required?: string[];
  items?: Node;
  anyOf?: Node[];
  const?: unknown;
  enum?: unknown[];
  additionalProperties?: Node | boolean;
  patternProperties?: Record<string, Node>;
  minimum?: number;
  maximum?: number;
  exclusiveMinimum?: number;
};

function typeOf(n: Node): string {
  if (n.const !== undefined) return `\`${JSON.stringify(n.const)}\``;
  if (n.anyOf) return n.anyOf.map(typeOf).join(" \\| ");
  if (n.type === "array") return `${n.items ? typeOf(n.items) : "any"}[]`;
  if (n.patternProperties) return `map of ${typeOf(Object.values(n.patternProperties)[0]!)}`;
  if (n.type === "object" && !n.properties) return "object";
  if (n.type === "object") return "object";
  return n.type ?? "any";
}

function bounds(n: Node): string {
  const b: string[] = [];
  if (n.minimum !== undefined) b.push(`≥ ${n.minimum}`);
  if (n.exclusiveMinimum !== undefined) b.push(`> ${n.exclusiveMinimum}`);
  if (n.maximum !== undefined) b.push(`≤ ${n.maximum}`);
  return b.length ? ` (${b.join(", ")})` : "";
}

function rows(n: Node, prefix: string, out: string[], depth = 0): void {
  if (depth > 4) return;
  // Unions of objects (e.g. field element kinds) are listed per variant.
  if (n.anyOf && n.anyOf.every((v) => v.properties)) {
    for (const v of n.anyOf) {
      const kind = v.properties?.kind?.const ?? v.properties?.type?.const;
      rows(v, kind ? `${prefix}〈${String(kind)}〉` : prefix, out, depth + 1);
    }
    return;
  }
  const props = n.properties ?? (n.type === "array" && n.items?.properties ? n.items.properties : undefined);
  const req = new Set(n.properties ? n.required ?? [] : n.items?.required ?? []);
  if (!props) {
    if (n.type === "array" && n.items?.anyOf) rows(n.items, `${prefix}[]`, out, depth + 1);
    return;
  }
  const base = n.type === "array" ? `${prefix}[]` : prefix;
  for (const [key, child] of Object.entries(props)) {
    const path = base ? `${base}.${key}` : key;
    const desc = (child.description ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
    out.push(`| \`${path}\` | ${typeOf(child)}${bounds(child)} | ${req.has(key) ? "yes" : ""} | ${desc} |`);
    if (child.properties || (child.type === "array" && (child.items?.properties || child.items?.anyOf)) || child.anyOf?.every((v) => v.properties))
      rows(child, path, out, depth + 1);
  }
}

const md: string[] = [
  "# Schemas",
  "",
  "<!-- Generated by `npm run export-schemas` from packages/schema/src. Do not edit by hand. -->",
  "",
  "GoldSim's data is JSON validated against these schemas. They are defined once in TypeScript with [TypeBox](https://github.com/sinclairzx81/typebox) (`packages/schema/src/`), which gives both the JSON Schema and the TypeScript types. The JSON Schema files in [`docs/schemas/`](schemas/) are for editors, other tools, and Claude.",
  "",
  "- Units are SI: meters, seconds, kilograms, radians. Headings are counter-clockwise from +x.",
  "- Validate a game module folder with `npm run validate-game -- <folder>` (schemas plus cross-file checks).",
  "- Field elements are authored from the blue side; `mirror: true` generates the red copy (`<id>.blue` / `<id>.red`).",
  "- Robot designs are never checked against robot-construction rules (PRD §8.6). Only values the sim needs to run are checked.",
  "",
  "| Schema | File | What it is |",
  "|---|---|---|",
  ...schemas.map((s) => `| ${s.name} | [\`${s.file}\`](schemas/${s.file}) | ${s.what} |`),
  "",
];

for (const s of schemas) {
  md.push(`## ${s.name}`, "", s.what, "", `File: [\`docs/schemas/${s.file}\`](schemas/${s.file})`, "");
  const out: string[] = [];
  rows(plain(s.schema), "", out);
  if (out.length) md.push("| Field | Type | Required | Description |", "|---|---|---|---|", ...out, "");
}

writeFileSync(join(root, "docs", "SCHEMAS.md"), md.join("\n"));
console.log(`Wrote ${schemas.length} schemas to ${outDir} and docs/SCHEMAS.md`);
