import { Type, type Static } from "@sinclair/typebox";

/** A number with a description. Descriptions are written for LLM and student readers. */
export const Num = (description: string, opts: { minimum?: number; maximum?: number; exclusiveMinimum?: number } = {}) =>
  Type.Number({ description, ...opts });

export const Alliance = Type.Union([Type.Literal("blue"), Type.Literal("red")], {
  description: "Alliance color. The field is authored from the blue side; red elements are generated by mirroring.",
});
export type Alliance = Static<typeof Alliance>;

export const Vec2 = Type.Object(
  { x: Num("meters"), y: Num("meters") },
  { description: "A point in meters." },
);
export type Vec2 = Static<typeof Vec2>;

export const Pose = Type.Object(
  {
    x: Num("meters"),
    y: Num("meters"),
    theta: Num("heading in radians, counter-clockwise from +x"),
  },
  { description: "Position and heading." },
);
export type Pose = Static<typeof Pose>;

export const RectShape = Type.Object(
  {
    type: Type.Literal("rect"),
    x: Num("center x in meters"),
    y: Num("center y in meters"),
    length: Num("size along x before rotation, meters", { exclusiveMinimum: 0 }),
    width: Num("size along y before rotation, meters", { exclusiveMinimum: 0 }),
    theta: Type.Optional(Num("rotation in radians (default 0)")),
  },
  { description: "Rectangle given by its center and size." },
);

export const CircleShape = Type.Object(
  {
    type: Type.Literal("circle"),
    x: Num("center x in meters"),
    y: Num("center y in meters"),
    radius: Num("meters", { exclusiveMinimum: 0 }),
  },
  { description: "Circle given by its center and radius." },
);

export const PolygonShape = Type.Object(
  {
    type: Type.Literal("polygon"),
    points: Type.Array(Vec2, { minItems: 3, description: "Vertices in order (convex for colliders)." }),
  },
  { description: "Polygon given by its vertices." },
);

export const Shape = Type.Union([RectShape, CircleShape, PolygonShape]);
export type Shape = Static<typeof Shape>;
export type RectShape = Static<typeof RectShape>;
export type CircleShape = Static<typeof CircleShape>;
export type PolygonShape = Static<typeof PolygonShape>;
